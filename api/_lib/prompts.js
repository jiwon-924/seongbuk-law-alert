// AI 가 붙인 근거 이름 중 실제로 준 조각만 남긴다
// 「근거 3」 같은 번호, 이름 전체, 「문서 · 소제목」 일부를 모두 받아 준다
export function keepKnown(list, chs) {
  const names = chs.map(sourceName);
  const one = (raw) => {
    const n = raw.trim();
    const num = n.match(/근거\s*(\d+)/);
    if (num && names[Number(num[1]) - 1]) return names[Number(num[1]) - 1];
    const whole = names.find((k) => k === n || n.includes(k) || (n.length > 10 && k.includes(n)));
    if (whole) return whole;
    const i = chs.findIndex((c) => n.includes(c['소제목'][0]) && n.includes(c['문서'].slice(0, 6)));
    return i >= 0 ? names[i] : undefined;
  };
  const out = (Array.isArray(list) ? list : [list]).filter(Boolean).map(String).map(one).filter(Boolean);
  return [...new Set(out)];
}
