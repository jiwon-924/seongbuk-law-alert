import { sourceName } from './data.js';

export const CONTACT = '성북구 청소행정과 02-2241-4400 (답변참고문서 기본 정보, 2026년 11월 기준)';

export const SYSTEM = `너는 성북구청 조례 담당 공무원의 검토를 돕는 심사 보조 AI다.
규칙
1. 아래 [근거 조각]에 있는 내용으로만 답한다. 일반 지식이나 추측을 더하지 않는다.
2. 조각에 없는 내용은 「문서에 없음」이라고 쓰고 문의처(${CONTACT})를 안내한다.
3. 판단·사유·초안마다 근거 조각 이름을 [근거 조각]의 「이름:」 뒤 글자 그대로 붙인다.
4. 개정 필요 여부를 단정하지 않는다. 「검토 필요」「검토 권고」로 쓰고, 최종 판단은 담당자가 한다고 본다.
5. 한국어 쉬운 말로 쓴다. 법령 문구를 옮길 때는 조각의 글자를 그대로 쓴다.
6. 출력은 요청한 JSON 객체 하나만 쓴다. 다른 글을 앞뒤에 붙이지 않는다.`;

export function context(chs) {
  return chs.map((c, i) => `[근거 ${i + 1}] 이름: ${sourceName(c)}\n자료: ${c['자료']}${c['판본'] ? ` · 판본: ${c['판본']}` : ''}${c['시행'] ? ` · 시행 ${c['시행']}` : ''}\n${c['본문']}`).join('\n\n---\n\n');
}

export function analyzePrompt(cs, chs) {
  return `[근거 조각]
${context(chs)}

[검토 요청]
${cs.시행일자} ${cs.법령} ${cs.법령조문}이 바뀌었다(${cs.개정후.판본}).
대조할 조례: ${cs.조례} ${cs.조례판본}.
이 개정이 조례에 맡긴(위임한) 사항이 그 조례에 이미 있는지 대조하고, 검토할 조례 조문과 그 사유를 정리하라.
조례에 규정이 없으면 그 때문에 생기는 문제(근거 공백)도 조각에 있는 범위에서 적어라.
길이: 검토조문은 3개 이내, 사유는 2문장 이내, 근거는 줄마다 3개 이내, 확인할점은 3개 이내.

[출력 JSON 형식]
{
  "요약": "담당자가 한 번에 읽을 2~3문장",
  "검토조문": [
    { "법령조문": "법령 조문", "조례조문": "대조한 조례 조문 또는 '해당 규정 없음'", "판단": "검토 필요 | 검토 권고 | 해당 없음 | 문서에 없음", "사유": "쉬운 말 사유", "근거": ["근거 조각 이름"] }
  ],
  "확인할점": ["담당자가 원문으로 직접 확인할 것"]
}`;
}

